// CI (lint and breaking-change) run results for the Hades schema registry.
//
// When a commit is pushed, the upload handler runs buf lint, and buf breaking
// against the previous commit when the module has breaking checks enabled.
// Both run synchronously and a violation rejects the push, so a commit that
// exists in the registry has already passed the checks configured for its
// module at that time. The result is recorded as a CIRun keyed by
// (module, commit_hash), in the same transaction that creates the commit.
//
// It follows that every stored CIRun has passed. A rejected push produces no
// commit, and a record is keyed by the commit hash, so there is nothing to
// attach a failure to. The lint_errors and breaking_errors fields exist for a
// future non-blocking check mode and are empty today. No record is written at
// all when linting is disabled for the deployment: a row claiming "passed" for
// checks that never ran would be worse than no row.

