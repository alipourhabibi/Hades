// In-app notification API for the Hades schema registry.
//
// Notifications are user-facing alerts about events on resources the user
// cares about. They are created server-side and delivered via polling.
//
// Two events raise them today:
//
//   commit.pushed   on every owner of the module and, when an organisation
//                   owns it, on each of its members, except whoever pushed
//   sdk.succeeded   on the author of the commit, when an SDK job finishes
//   sdk.failed      on the same recipient, when an SDK job fails
//
// Raising a notification is best effort and never fails the operation that
// triggered it: the push or the job outcome is already durable by then.

